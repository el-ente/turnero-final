import { useState } from 'react'
import reactLogo from './assets/react.svg'
import viteLogo from './assets/vite.svg'
import heroImg from './assets/hero.png'
import { db } from './lib/firebase'
import { doc, getDoc, setDoc } from 'firebase/firestore'
import './App.css'

function App() {
  const [count, setCount] = useState(0)
  const [firestoreData, setFirestoreData] = useState<string | null>(null)

  const readFromFirestore = async () => {
    try {
      const docRef = doc(db, 'test', 'message')
      const docSnap = await getDoc(docRef)
      if (docSnap.exists()) {
        setFirestoreData(docSnap.data().message || 'No message field')
      } else {
        setFirestoreData('Document does not exist')
      }
    } catch (error: unknown) {
      setFirestoreData(`Error: ${ (error as Error).message }`)
    }
  }

  const writeToFirestore = async () => {
    try {
      await setDoc(doc(db, 'test', 'message'), {
        message: 'Hola desde Firebase! Las env vars funcionan correctamente.'
      })
      setFirestoreData('Documento escrito exitosamente')
    } catch (error: unknown) {
      setFirestoreData(`Error escribiendo: ${ (error as Error).message }`)
    }
  }

  return (
    <>
      <section id="center">
        <div className="hero">
          <img src={heroImg} className="base" width="170" height="179" alt="" />
          <img src={reactLogo} className="framework" alt="React logo" />
          <img src={viteLogo} className="vite" alt="Vite logo" />
        </div>
        <div>
          <h1>Get started</h1>
          <p>
            Edit <code>src/App.tsx</code> and save to test <code>HMR</code>
          </p>
        </div>
        <button
          className="counter"
          onClick={() => setCount((count) => count + 1)}
        >
          Count is {count}
        </button>
        <button
          className="counter"
          onClick={readFromFirestore}
        >
          Leer de Firestore
        </button>
        <button
          className="counter"
          onClick={writeToFirestore}
        >
          Escribir a Firestore
        </button>
        {firestoreData && <p>Firestore data: {firestoreData}</p>}
      </section>

      <div className="ticks"></div>

      <section id="next-steps">
        <div id="docs">
          <svg className="icon" role="presentation" aria-hidden="true">
            <use href="/icons.svg#documentation-icon"></use>
          </svg>
          <h2>Documentation</h2>
          <p>Your questions, answered</p>
          <ul>
            <li>
              <a href="https://vite.dev/" target="_blank">
                <img className="logo" src={viteLogo} alt="" />
                Explore Vite
              </a>
            </li>
            <li>
              <a href="https://react.dev/" target="_blank">
                <img className="button-icon" src={reactLogo} alt="" />
                Learn more
              </a>
            </li>
          </ul>
        </div>
        <div id="social">
          <svg className="icon" role="presentation" aria-hidden="true">
            <use href="/icons.svg#social-icon"></use>
          </svg>
          <h2>Connect with us</h2>
          <p>Join the Vite community</p>
          <ul>
            <li>
              <a href="https://github.com/vitejs/vite" target="_blank">
                <svg
                  className="button-icon"
                  role="presentation"
                  aria-hidden="true"
                >
                  <use href="/icons.svg#github-icon"></use>
                </svg>
                GitHub
              </a>
            </li>
            <li>
              <a href="https://chat.vite.dev/" target="_blank">
                <svg
                  className="button-icon"
                  role="presentation"
                  aria-hidden="true"
                >
                  <use href="/icons.svg#discord-icon"></use>
                </svg>
                Discord
              </a>
            </li>
            <li>
              <a href="https://x.com/vite_js" target="_blank">
                <svg
                  className="button-icon"
                  role="presentation"
                  aria-hidden="true"
                >
                  <use href="/icons.svg#x-icon"></use>
                </svg>
                X.com
              </a>
            </li>
            <li>
              <a href="https://bsky.app/profile/vite.dev" target="_blank">
                <svg
                  className="button-icon"
                  role="presentation"
                  aria-hidden="true"
                >
                  <use href="/icons.svg#bluesky-icon"></use>
                </svg>
                Bluesky
              </a>
            </li>
          </ul>
        </div>
      </section>

      <div className="ticks"></div>
      <section id="spacer"></section>
    </>
  )
}

export default App
